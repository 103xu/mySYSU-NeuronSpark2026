"""
NS-2026-02 文本标准化模块
面向字符级 EM/F1 评测对齐
"""
import re
import unicodedata


# ── 全半角/标点/括号映射 ──────────────────────────────

_FULLWIDTH_MAP = {
    "０": "0", "１": "1", "２": "2", "３": "3", "４": "4",
    "５": "5", "６": "6", "７": "7", "８": "8", "９": "9",
    "Ａ": "A", "Ｂ": "B", "Ｃ": "C", "Ｄ": "D", "Ｅ": "E",
    "Ｆ": "F", "Ｇ": "G", "Ｈ": "H", "Ｉ": "I", "Ｊ": "J",
    "Ｋ": "K", "Ｌ": "L", "Ｍ": "M", "Ｎ": "N", "Ｏ": "O",
    "Ｐ": "P", "Ｑ": "Q", "Ｒ": "R", "Ｓ": "S", "Ｔ": "T",
    "Ｕ": "U", "Ｖ": "V", "Ｗ": "W", "Ｘ": "X", "Ｙ": "Y",
    "Ｚ": "Z", "ａ": "a", "ｂ": "b", "ｃ": "c", "ｄ": "d",
    "ｅ": "e", "ｆ": "f", "ｇ": "g", "ｈ": "h", "ｉ": "i",
    "ｊ": "j", "ｋ": "k", "ｌ": "l", "ｍ": "m", "ｎ": "n",
    "ｏ": "o", "ｐ": "p", "ｑ": "q", "ｒ": "r", "ｓ": "s",
    "ｔ": "t", "ｕ": "u", "ｖ": "v", "ｗ": "w", "ｘ": "x",
    "ｙ": "y", "ｚ": "z",
    "（": "(", "）": ")", "【": "[", "】": "]",
    "《": "<", "》": ">", "｛": "{", "｝": "}",
    "！": "!", "＂": '"', "＃": "#", "＄": "$",
    "％": "%", "＆": "&", "＇": "'", "＊": "*",
    "＋": "+", "，": ",", "－": "-", "．": ".",
    "／": "/", "：": ":", "；": ";", "＜": "<",
    "＝": "=", "＞": ">", "？": "?", "＠": "@",
    "＾": "^", "＿": "_", "｀": "`", "～": "~",
    "　": " ",
}


def normalize(text: str) -> str:
    """比赛评测级标准化"""
    if not text:
        return ""

    # Unicode NFKC
    text = unicodedata.normalize("NFKC", text)

    # 全角→半角
    text = "".join(_FULLWIDTH_MAP.get(ch, ch) for ch in text)

    # 英文小写
    text = text.lower()

    # 删除空白字符
    text = re.sub(r"\s+", "", text)

    # 删除所有标点（评测只关注实体字符）
    _PUNCT = r"[，。！？、；：""''（）【】《》…—·,.!?;:\"'()\[\]{}<>@#$%^&*+=/\\|`~_-]"
    text = re.sub(_PUNCT, "", text)

    return text


# ── 答案后处理：去除前缀 ────────────────────────────────

_PREFIX_PATTERNS = [
    re.compile(p) for p in [
        r"^根据(资料|规定|制度|知识库|规则)[，,]?",
        r"^文中提到[，,]?",
        r"^答案是?[：:]?\s*",
        r"^回答[：:]?\s*",
        r"^答案?为[：:]?\s*",
        r"^答[：:]?\s*",
    ]
]


def clean_answer(text: str) -> str:
    """去除答案中的解释性前缀"""
    for pat in _PREFIX_PATTERNS:
        text = pat.sub("", text)
    return text.strip()


# ── 别名映射表 ─────────────────────────────────────────

_ALIAS_MAP = {
    "u.s.a": "美国",
    "usa": "美国",
    "中华人民共和国": "中国",
    "prc": "中国",
}


def apply_alias(text: str) -> str:
    """应用别名映射"""
    for src, dst in _ALIAS_MAP.items():
        text = text.replace(src, dst)
    return text


# ── 统一处理流程 ───────────────────────────────────────

def canonicalize(text: str) -> str:
    """完整标准化流水线"""
    text = clean_answer(text)
    text = apply_alias(text)
    text = normalize(text)
    return text
